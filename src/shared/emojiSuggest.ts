const KEYWORD_EMOJI: [RegExp, string][] = [
  [/покупк|магазин|купить|молоко|хлеб|продукт/i, '🛒'],
  [/встреч|созвон|звонок|митинг|meeting/i, '📅'],
  [/идея|придума|concept/i, '💡'],
  [/код|баг|bug|разработ|программ|debug/i, '💻'],
  [/деньги|бюджет|финанс|оплат|счет|счёт/i, '💰'],
  [/книга|читать|прочитать|статья/i, '📚'],
  [/еда|рецепт|готовить|ужин|обед|завтрак/i, '🍳'],
  [/путешеств|поездка|аэропорт|билет|отпуск/i, '✈️'],
  [/задач|todo|список дел|план/i, '✅'],
  [/важно|срочно|priority/i, '⚠️'],
  [/подарок|день рождения|праздник/i, '🎁'],
  [/здоровье|врач|таблетк|болезн/i, '💊'],
  [/спорт|тренировк|зал|фитнес/i, '🏋️'],
  [/музык|песня|плейлист/i, '🎵'],
  [/фильм|кино|сериал/i, '🎬'],
  [/работа|проект|дедлайн|офис/i, '💼'],
  [/учеба|учёба|экзамен|лекция|универ/i, '🎓'],
  [/дом|квартира|ремонт/i, '🏠'],
  [/машина|авто|транспорт/i, '🚗'],
  [/пароль|логин|аккаунт/i, '🔑']
]

export function suggestEmojis(text: string, max = 6): string[] {
  const matches: string[] = []
  for (const [pattern, emoji] of KEYWORD_EMOJI) {
    if (pattern.test(text) && !matches.includes(emoji)) {
      matches.push(emoji)
      if (matches.length >= max) break
    }
  }
  return matches
}

