import type { OcrPreset } from './types'

export interface OcrPresetInfo {
  id: OcrPreset
  label: string
  description: string
}

export const OCR_PRESETS: OcrPresetInfo[] = [
  { id: 'asis', label: 'Как есть', description: 'Минимум правок — только явные ошибки распознавания' },
  { id: 'formal', label: 'Формально', description: 'Грамотная пунктуация, деловой стиль' },
  { id: 'casual', label: 'Свободно', description: 'Лёгкий разговорный стиль, естественные формулировки' },
  { id: 'structured', label: 'Структурно', description: 'Явно оформляет списки и таблицы, где это уместно' }
]

const PRESET_INSTRUCTIONS: Record<OcrPreset, string> = {
  asis: 'Исправляй только очевидные опечатки распознавания. Сохраняй исходную пунктуацию и формулировки, не переписывай текст.',
  formal: 'Причёсывай текст в деловом стиле: грамотная пунктуация, полные формулировки, без сленга и лишних междометий.',
  casual: 'Причёсывай текст в лёгком разговорном стиле: естественные формулировки, можно упростить канцеляризмы.',
  structured: 'Активно выделяй структуру: списки, таблицы, заголовки — используй соответствующие типы блоков.'
}

const SCHEMA_DESCRIPTION = `Верни результат СТРОГО в виде JSON-массива блоков (без markdown-разметки, без пояснений, только сам массив). Каждый блок — объект с полем "type":
- {"type":"heading","text":"..."} — заголовок или явно выделенный подзаголовок
- {"type":"paragraph","text":"..."} — обычный текст/абзац
- {"type":"list","ordered":true|false,"items":["...","..."]} — список или перечисление
- {"type":"table","rows":[["ячейка","ячейка"],["ячейка","ячейка"]]} — таблица или несколько выровненных колонок текста
- {"type":"button","text":"..."} — текст на кнопке или элементе интерфейса (не основной текст, а именно надпись на UI-элементе вроде кнопки/вкладки/чипа)
- {"type":"label","text":"..."} — короткая подпись, ярлык, метка поля

Правила:
- Если на изображении интерфейс приложения (кнопки, вкладки, поля) — размечай кнопки как "button", не смешивай их с обычным текстом.
- Если видишь таблицу или несколько колонок данных — используй "table", не сливай колонки в одну строку.
- Если видишь нумерованный или маркированный список — используй "list".
- Не добавляй ничего от себя, не переводи текст на другой язык, не выдумывай информацию, которой нет на изображении.
- Если текста на изображении нет, верни пустой массив [].`

export function buildOcrPrompt(preset: OcrPreset, existingContext?: string): string {
  const parts = [
    'Распознай весь текст и элементы интерфейса на этом изображении (OCR + понимание структуры).',
    PRESET_INSTRUCTIONS[preset],
    SCHEMA_DESCRIPTION
  ]

  if (existingContext && existingContext.trim()) {
    parts.push(
      `Это распознавание добавляется к уже существующей заметке. Вот конец её текущего содержимого для контекста (не повторяй его в ответе, просто учти при формулировках, чтобы новый текст логично продолжал уже написанное): "${existingContext.trim().slice(-800)}"`
    )
  }

  return parts.join('\n\n')
}

export function buildTextFormatPrompt(preset: OcrPreset, rawText: string, existingContext?: string): string {
  const parts = [
    'Ниже — текст, уже распознанный локальным OCR-движком с изображения (может содержать опечатки распознавания). Твоя задача — причесать его и разметить по структуре, не придумывая ничего нового.',
    PRESET_INSTRUCTIONS[preset],
    SCHEMA_DESCRIPTION,
    `Вот исходный распознанный текст:\n"""\n${rawText.slice(0, 6000)}\n"""`
  ]

  if (existingContext && existingContext.trim()) {
    parts.push(
      `Это добавляется к уже существующей заметке. Конец её текущего содержимого для контекста (не повторяй в ответе): "${existingContext.trim().slice(-800)}"`
    )
  }

  return parts.join('\n\n')
}
