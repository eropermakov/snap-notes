const SCHEMA_DESCRIPTION = `Верни результат СТРОГО в виде JSON-массива блоков (без markdown-разметки, без пояснений, только сам массив). Каждый блок — объект с полем "type":
- {"type":"heading","text":"..."} — заголовок или явно выделенный подзаголовок
- {"type":"paragraph","text":"..."} — обычный текст/абзац
- {"type":"list","ordered":true|false,"items":["...","..."]} — список или перечисление
- {"type":"table","rows":[["ячейка","ячейка"],["ячейка","ячейка"]]} — таблица или несколько выровненных колонок текста
- {"type":"label","text":"..."} — короткая подпись, ярлык, метка поля
- {"type":"image","bbox":[ymin,xmin,ymax,xmax]} — настоящая фотография, иллюстрация, картинка, отдельный визуальный контент (НЕ иконка интерфейса, НЕ логотип, НЕ декоративная рамка). bbox — координаты прямоугольника в промилле (целые числа 0-1000) от размера всего изображения, в порядке [ymin,xmin,ymax,xmax], где 0 — верхний/левый край, 1000 — нижний/правый край

КРИТИЧЕСКИ ВАЖНО:
- Возвращай блоки СТРОГО в том порядке, в котором они расположены на странице сверху вниз — включая image-блоки на их точном месте в последовательности между текстовыми блоками. Ничего не переставляй.
- Помечай как "image" только настоящие фотографии/иллюстрации/картинки — не мелкие иконки кнопок, не логотипы, не элементы оформления интерфейса.
- Текст самого изображения не выдумывай и не пересказывай — просто отметь его границы через bbox, текст рядом с ним распознавай как обычно.
- Не добавляй ничего от себя, не переводи текст на другой язык, не выдумывай информацию, которой нет на изображении.
- Сохраняй исходную пунктуацию и формулировки текста, минимальные правки только для явных ошибок распознавания.
- Если на изображении вообще ничего нет — верни пустой массив [].`

export function buildDocumentPrompt(): string {
  return [
    'Разбери это изображение (целиком, включая все фотографии внутри него) на последовательность блоков — текст и фотографии — как если бы ты готовил документ по мотивам этой страницы.',
    SCHEMA_DESCRIPTION
  ].join('\n\n')
}
